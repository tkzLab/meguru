/**
 * meguru — 光の粒の減衰カーブ
 *
 * THREE も document も import しない純関数だけを置く。
 * render.js からスプライト生成に使い、Node の `node --test` からも直接検証する。
 *
 * 【なぜローレンツ型なのか】
 * 接写のムードボード（work/moodboard-closeup.png）で、孤立した暖色の粒 50 個の
 * 半径方向プロファイルを平均したところ（R=24px で正規化）:
 *
 *   r  : 0     2     4     6     8    10    12    16    20    24
 *   値 : 1.00  0.48  0.18  0.10  0.05  0.03  0.02  0.01  0.00  0.00
 *
 * これは「鋭い芯 ＋ 弱く長い裾」で、単一のべき乗カーブでは表せない。
 *   1/(1 + (t/a)^2)  … 残差二乗和 0.0002   ← 採用
 *   (1 - t)^2        … 残差二乗和 0.9241
 * 旧式は r=4px で 0.69 を返す（実測 0.18 の 3.8 倍）。裾が太すぎるため、
 * 粒が「細かい点」ではなく「綿の塊」に見えていた。
 *
 * 検証は test/falloff.test.mjs（旧式がこの assert に落ちることも確認している）。
 */

/** 接写ムードボードの実測プロファイル。テストと本実装の唯一の正本。 */
export const MEASURED_PROFILE = [
  [0, 1.00], [2, 0.48], [4, 0.18], [6, 0.10], [8, 0.05],
  [10, 0.03], [12, 0.02], [16, 0.01], [20, 0.00], [24, 0.00],
];

/** 上のプロファイルを測った半径（px）。t = r / MEASURED_RADIUS で正規化する。 */
export const MEASURED_RADIUS = 24;

/** 実測に最も合う芯の細さ（半値半径 ÷ スプライト半径）。実測 1.91/24 = 0.080。 */
export const MEASURED_CORE = 0.080;

/**
 * スプライトの不透明度。
 *
 * @param {number} t 中心からの距離。0 = 中心、1 = スプライトの縁
 * @param {number} a 芯の細さ（半値半径の割合）。小さいほど芯が鋭く裾が長い
 * @returns {number} 0..1。t >= 1 でちょうど 0（スプライトの四角い継ぎ目を出さないため）
 */
export function glowFalloff(t, a) {
  if (!(t > 0)) return t === 0 ? 1 : 0; // NaN も 0 に落とす
  if (t >= 1) return 0;
  // t=1 でちょうど 0 になるよう、縁での値を引いてから正規化し直す。
  // これを省くと縁に 0.6% ほどの段差が残り、四角いスプライトの輪郭が見える。
  const edge = 1 / (1 + 1 / (a * a));
  const v = 1 / (1 + (t / a) * (t / a));
  return (v - edge) / (1 - edge);
}

/** 旧実装。テストの canary（これが実測に合わないことを確認する）専用。 */
export function legacyFalloff(t, power) {
  if (t >= 1) return 0;
  return Math.pow(1 - t, power);
}
